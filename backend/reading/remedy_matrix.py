def get_situational_remedies(planet: str, age: int, situation: str, location_type: str, financial_level: str) -> dict:
    """
    Generate 3-tier remedies adapted to user's real life situation.
    Never suggest what the user cannot do or afford.
    """
    base = PLANET_REMEDIES.get(planet, {})
    if not base:
        return {"free": [], "affordable": [], "premium": []}

    free_remedies = []
    affordable_remedies = []
    premium_remedies = []

    # --- FREE REMEDIES (works for everyone, everywhere) ---
    free_remedies.append(f"Mantra: {base['mantra']}")
    free_remedies.append(f"Behavioral: {base['behavioral']}")

    if age < 70:
        free_remedies.append(f"Fast on {base['fast_day']} — even partial fast (skip one meal)")

    if location_type == "abroad":
        free_remedies.append(f"Wear {base['color']} on {base['fast_day']}")
        free_remedies.append("Donate to any local charity or food bank on the prescribed day")
        free_remedies.append("Listen to the planet mantra on YouTube while working (earphones)")
    else:
        free_remedies.append(f"Donate: {base['charity']}")
        free_remedies.append(f"Tree/Nature remedy: {base['tree']}")

    if age >= 60:
        free_remedies.append(f"Simple home puja to {base['deity']} — no travel required")

    # --- AFFORDABLE REMEDIES (₹50-1000) ---
    if financial_level != "struggling":
        if age < 70 and location_type != "abroad":
            affordable_remedies.append(
                f"Rudraksha: {base['rudraksha']} (₹200-800 — wear after energizing on {base['fast_day']})"
            )
        affordable_remedies.append(f"Yantra: {planet} Yantra (₹200-500 — place in home puja space facing East)")
        if location_type != "abroad":
            affordable_remedies.append(f"Metal: Keep a {base['metal']} item at home (no cost if already owned)")

    # --- PREMIUM REMEDIES (only if financially able) ---
    if financial_level == "high" and age >= 18:
        if "gemstone" in base:
            premium_remedies.append(f"Gemstone (consult astrologer first): {base['gemstone']}")
        if location_type != "abroad":
            premium_remedies.append(f"Graha Shanti Puja for {planet} (₹3,000-15,000 at temple)")

    # Remove premium if student or struggling
    if situation in ["student", "struggling"] or financial_level == "low":
        premium_remedies = []
        affordable_remedies = affordable_remedies[:1]

    return {
        "free": free_remedies,
        "affordable": affordable_remedies,
        "premium": premium_remedies,
        "note": "Start with free remedies for 40 days. Results are measured in mindset shifts, reduced anxiety, and opened opportunities — not miracles.",
    }

